// Writes a migration that seeds the exported core plugin definitions as
// reference data (decision R8: a plugin is software, not content). Used once
// per new core version: a migration is never edited after it is applied. The files
// themselves go to the store with `npm run core:plugins:upload` (decision R13).
// Usage: node scripts/core-plugins-migration.mjs <timestamp>   e.g. 20260918000300
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const stamp = process.argv[2];
if (!/^\d{14}$/.test(stamp ?? "")) {
  console.error("usage: node scripts/core-plugins-migration.mjs <YYYYMMDDhhmmss>");
  process.exit(1);
}

const dir = join(root, "plugins", "core");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".lisanplugin.json"))
  .sort();
let sql = `-- =============================================================================
-- LisanHub — core plugin definitions (decision R7; reference data, never content — R8)
--
-- Generated by scripts/core-plugins-migration.mjs from plugins/core/*.lisanplugin.json,
-- which the studio pipeline produced (scripts/core-plugins.ts). owner_id is null:
-- these belong to the platform. The definition itself is a file in the store
-- (decision R13): \`npm run core:plugins:upload\` puts each exported file at the key
-- the rows below name, and tests/db/core-plugins.test.ts checks key and sha256
-- against the exported file.
-- =============================================================================

`;
for (const file of files) {
  const text = readFileSync(join(dir, file), "utf8");
  const { sha256, plugin_id, version, schema_version } = JSON.parse(text);
  const key = `plugins/core/${plugin_id}-${version}.lisanplugin.json`;
  sql += `-- ${plugin_id} ${version} (sha256 ${sha256})
insert into public.plugins (plugin_id, owner_id, status, draft_key, draft_sha256, published_at)
values ('${plugin_id}', null, 'published', '${key}', '${sha256}', now())
on conflict (plugin_id) do update set draft_key = excluded.draft_key, draft_sha256 = excluded.draft_sha256;

insert into public.plugin_versions (plugin_id, version, schema_version, definition_key, definition_sha256, author_id, change_note)
select p.id, '${version}', ${schema_version}, '${key}', '${sha256}', null, 'core plugin'
  from public.plugins p
 where p.plugin_id = '${plugin_id}'
   and not exists (select 1 from public.plugin_versions v where v.plugin_id = p.id and v.version = '${version}');

update public.plugins p
   set current_version_id = v.id
  from public.plugin_versions v
 where v.plugin_id = p.id and v.version = '${version}' and p.plugin_id = '${plugin_id}';

`;
}
const out = join(root, "supabase", "migrations", `${stamp}_core_plugins.sql`);
writeFileSync(out, sql);
console.log(`wrote ${out} (${files.length} plugins) — then run: npm run core:plugins:upload`);
